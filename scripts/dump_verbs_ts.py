#!/usr/bin/env python3

from __future__ import annotations

import json
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from mechbench_runner import __version__  # noqa: E402
from mechbench_runner.verbs import CONSENT, EFFECTS, NOUNS, Arg, Verb  # noqa: E402

TYPES = ("str", "int", "float", "bool", "json", "pairs", "strs")


def _ts(value) -> str:
    return json.dumps(value, ensure_ascii=False)


def arg_of(a: Arg) -> dict:
    return {
        "name": a.name,
        "help": a.help,
        "type": a.type,
        "required": a.required,
        "positional": a.positional,
        "choices": list(a.choices),
        "local": a.local,
    }


def verb_of(v: Verb) -> dict:
    method, _, route = v.api.partition(" ")
    return {
        "noun": v.noun,
        "name": v.name,
        "help": v.help,
        "method": method,
        "route": route,
        "shape": v.shape,
        "effect": v.effect,
        "consentWhen": {k: list(vs) for k, vs in v.consent_when.items()},
        "local": v.local,
        "args": [arg_of(a) for a in v.args],
    }


def main() -> None:
    print(
        "// GENERATED by mechbench-runner scripts/dump_verbs_ts.py "
        f"({__version__}). Do not edit by hand."
    )
    print(
        "// The source is the verb registry, mechbench_runner/verbs/; "
        "re-run the script after changing it."
    )
    print()
    print("/** What a verb does to the platform. */")
    print("export type VerbEffect = " + " | ".join(_ts(k) for k in EFFECTS) + ";")
    print()
    print("export const VERB_EFFECTS: Record<VerbEffect, string> = {")
    for k, v in EFFECTS.items():
        print(f"  {k}: {_ts(v)},")
    print("};")
    print()
    print(
        "/** The effects a call needs the person's consent for: the "
        "platform's agent proposes it, and only the person's click makes it. */"
    )
    print("export const CONSENT_EFFECTS: VerbEffect[] = " + _ts(list(CONSENT)) + ";")
    print()
    print("export type RegistryArgType = " + " | ".join(_ts(t) for t in TYPES) + ";")
    print()
    print(
        "/** An argument of a verb. `local` names something on the caller's "
        "own machine (a file to read or write), which a caller without one "
        "leaves out. */"
    )
    print("export interface RegistryArg {")
    print("  name: string;")
    print("  help: string;")
    print("  type: RegistryArgType;")
    print("  required: boolean;")
    print("  positional: boolean;")
    print("  choices: string[];")
    print("  local: boolean;")
    print("}")
    print()
    print(
        "/** A verb of a noun: the API route it maps to, what it does "
        "(`effect`), and the argument values that make a call need consent "
        "(`consentWhen`, any of them; empty means every call does when the "
        "effect needs consent). `local` says it computes on the caller's "
        "machine. */"
    )
    print("export interface RegistryVerb {")
    print("  noun: string;")
    print("  name: string;")
    print("  help: string;")
    print('  method: "GET" | "POST" | "PUT" | "PATCH" | "DELETE";')
    print("  route: string;")
    print("  shape: string;")
    print("  effect: VerbEffect;")
    print("  consentWhen: Record<string, (string | number | boolean)[]>;")
    print("  local: boolean;")
    print("  args: RegistryArg[];")
    print("}")
    print()
    print("export interface RegistryNoun {")
    print("  name: string;")
    print("  help: string;")
    print("  verbs: RegistryVerb[];")
    print("  /** Lifecycle verbs it has not, and why. */")
    print("  absent: Record<string, string>;")
    print("}")
    print()
    print("export const VERB_REGISTRY: RegistryNoun[] = [")
    for n in NOUNS:
        print("  {")
        print(f"    name: {_ts(n.name)},")
        print(f"    help: {_ts(n.help)},")
        print(f"    absent: {_ts(dict(n.absent))},")
        print("    verbs: [")
        for v in n.verbs:
            print(f"      {_ts(verb_of(v))},")
        print("    ],")
        print("  },")
    print("];")


if __name__ == "__main__":
    main()
